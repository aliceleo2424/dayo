  function sets(card, language) {
    if (!card || !pools[language] || !pools[language][card.category]) return [];
    var seen = {};
    var rows = ((specific[language] || {})[card.id] || []).concat(pools[language][card.category]).filter(function (row) {
      var key = row[0].trim().toLowerCase();
      if (!key || seen[key]) return false;
      seen[key] = true; return true;
    }).map(function (row) { return { text: row[0], ko: row[1] }; });
    if (rows.length < 4) return [];
    var count = Math.ceil(rows.length / 6), size = Math.floor(rows.length / count), extra = rows.length % count;
    var result = [], offset = 0;
    for (var i = 0; i < count; i++) {
      var length = size + (i < extra ? 1 : 0);
      result.push(rows.slice(offset, offset + length)); offset += length;
    }
    return result;
  }
